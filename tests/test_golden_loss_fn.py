"""Golden-value regression tests.

These freeze the exact numeric output of today's loss_fn/train_model on a
small fixed synthetic dataset with a fixed RNG seed. They exist so the
Step 3 registry refactor (see dev/workplan.md) can be checked against
these same expected values afterward with default weights, to confirm the
restructuring alone produced no numeric change.

The expected values below were generated by running this exact test
against the pre-refactor code and recording the output; they are not
independently hand-derived.
"""

from functools import partial

import haiku as hk
import optax
import pytest
from jax import jit

from flow_model_training import loss_fn, train_model

OBS_WEIGHT = 1.0
DIST_WEIGHT = 0.1
ENT_WEIGHT = 0.01
TRAINING_STEPS = 5
RNG_SEED = 0
LEARNING_RATE = 0.1


def _run(small_training_fixture):
    dtuple, d_matrices, masked_densities, cells = small_training_fixture

    weights = {'obs': OBS_WEIGHT, 'dist': DIST_WEIGHT, 'ent': ENT_WEIGHT}

    bound_loss_fn = jit(
        partial(
            loss_fn,
            cells=cells,
            true_densities=masked_densities,
            d_matrices=d_matrices,
            weights=weights,
        )
    )

    key = hk.PRNGSequence(RNG_SEED)
    optimizer = optax.adam(LEARNING_RATE)

    return train_model(
        bound_loss_fn, optimizer, TRAINING_STEPS, cells, dtuple.weeks, key
    )


def test_golden_loss_dict(small_training_fixture):
    _, loss_dict = _run(small_training_fixture)

    expected = {
        "total": [
            0.667844295501709,
            0.5833374261856079,
            0.5109524726867676,
            0.4497908651828766,
            0.39857423305511475,
        ],
        "obs": [
            0.30914968252182007,
            0.23324818909168243,
            0.17423208057880402,
            0.12689657509326935,
            0.09026879072189331,
        ],
        "dist": [
            3.6815903186798096,
            3.5969924926757812,
            3.4622321128845215,
            3.321208953857422,
            3.1714730262756348,
        ],
        "ent": [
            0.946446418762207,
            0.9610010385513306,
            0.9502843618392944,
            0.9226634502410889,
            0.884188175201416,
        ],
    }

    assert loss_dict.keys() == expected.keys()
    for key, expected_values in expected.items():
        actual_values = loss_dict[key]
        assert len(actual_values) == len(expected_values)
        for actual, exp in zip(actual_values, expected_values):
            assert actual == pytest.approx(exp, rel=1e-5)


def test_golden_fitted_params(small_training_fixture):
    params, _ = _run(small_training_fixture)

    z0 = params["Flow_Model/Initial_Params"]["z0"]
    expected_z0 = [
        0.6468034386634827,
        0.8098920583724976,
        -0.4022241532802582,
        0.03401517495512962,
    ]
    for actual, exp in zip(z0.tolist(), expected_z0):
        assert actual == pytest.approx(exp, rel=1e-5)

    week1_z00 = float(params["Flow_Model/Week_1"]["z"][0, 0])
    assert week1_z00 == pytest.approx(-0.3869096040725708, rel=1e-5)
